-- Role names are unique regardless of case: per workspace for custom roles,
-- among themselves for default roles, and across the one admin plane. Two
-- partial indexes for workspace roles, because a NULL workspace_id would make
-- every default row distinct in one composite index.
CREATE UNIQUE INDEX "workspace_roles_custom_name_key"
    ON "workspace_roles" ("workspace_id", lower("name"))
    WHERE "workspace_id" IS NOT NULL;

CREATE UNIQUE INDEX "workspace_roles_default_name_key"
    ON "workspace_roles" (lower("name"))
    WHERE "workspace_id" IS NULL;

CREATE UNIQUE INDEX "admin_roles_lower_name_key"
    ON "admin_roles" (lower("name"));

-- A role's scope is fixed at insert. The tenant triggers below check a role's
-- workspace when a holding row is written; that check holds only while the
-- role cannot later move to another workspace, or become a default role.
CREATE FUNCTION "forbid_workspace_role_rescope"() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW."workspace_id" IS DISTINCT FROM OLD."workspace_id"
       OR NEW."is_system" IS DISTINCT FROM OLD."is_system" THEN
        RAISE EXCEPTION 'workspace role % cannot change its workspace or system flag', OLD."id"
            USING ERRCODE = 'check_violation';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER "workspace_roles_scope_immutable"
    BEFORE UPDATE OF "workspace_id", "is_system" ON "workspace_roles"
    FOR EACH ROW EXECUTE FUNCTION "forbid_workspace_role_rescope"();

-- A member, or an invitation, may hold a default role or a role of its own
-- workspace, and nothing else. A composite foreign key cannot say this —
-- a default role has no workspace to match — so it is this trigger. It is
-- what keeps workspace A's custom role off workspace B's member when the
-- service code is wrong.
CREATE FUNCTION "assert_workspace_role_in_tenant"() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM "workspace_roles" AS r
        WHERE r."id" = NEW."role_id"
          AND (r."workspace_id" IS NULL OR r."workspace_id" = NEW."workspace_id")
    ) THEN
        RAISE EXCEPTION 'workspace role % is not available in workspace %', NEW."role_id", NEW."workspace_id"
            USING ERRCODE = 'foreign_key_violation';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER "workspace_member_roles_role_tenant"
    BEFORE INSERT OR UPDATE OF "role_id", "workspace_id" ON "workspace_member_roles"
    FOR EACH ROW EXECUTE FUNCTION "assert_workspace_role_in_tenant"();

CREATE TRIGGER "workspace_invitations_role_tenant"
    BEFORE INSERT OR UPDATE OF "role_id", "workspace_id" ON "workspace_invitations"
    FOR EACH ROW EXECUTE FUNCTION "assert_workspace_role_in_tenant"();
